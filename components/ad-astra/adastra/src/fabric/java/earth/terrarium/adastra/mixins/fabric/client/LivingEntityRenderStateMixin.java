package earth.terrarium.adastra.mixins.fabric.client;

import earth.terrarium.adastra.client.AdAstraRenderState;
import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.world.entity.LivingEntity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(LivingEntityRenderer.class)
public class LivingEntityRenderStateMixin {
    @Inject(method = "extractRenderState(Lnet/minecraft/world/entity/LivingEntity;Lnet/minecraft/client/renderer/entity/state/LivingEntityRenderState;F)V", at = @At("TAIL"))
    private void adastra$keepEntity(LivingEntity entity, LivingEntityRenderState state, float partialTick, CallbackInfo ci) {
        state.setData(AdAstraRenderState.LIVING_ENTITY, entity);
    }
}
